"""Render the stills that ship in public/ from the live 3D scene, with headless Chrome:

  public/fallback/campus.jpg  the campus as shown when the browser has no WebGL
  src/content/fallback.ts     where the four module labels point in that image
  public/og.jpg               the social card (1200 x 630)

Run it against a running dev or preview server:  python scripts/capture_stills.py [http://localhost:5173/]
"""

import html
import json
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
BASE = sys.argv[1] if len(sys.argv) > 1 else "http://localhost:5173/"
CHROME = os.environ.get("CHROME", r"C:\Program Files\Google\Chrome\Application\chrome.exe")
# the headless viewport is a little shorter than the window, so the page draws at a fixed size and
# the window leaves room below it
SLACK = 120


def chrome(url, width, height, *action):
    with tempfile.TemporaryDirectory() as profile:
        return subprocess.run(
            [
                CHROME,
                "--headless=new",
                f"--user-data-dir={profile}",
                f"--window-size={width},{height + SLACK}",
                "--force-device-scale-factor=1",
                # the camera jumps straight to its shot instead of flying there
                "--force-prefers-reduced-motion",
                "--enable-unsafe-swiftshader",
                "--hide-scrollbars",
                "--virtual-time-budget=40000",
                *action,
                url,
            ],
            capture_output=True,
            text=True,
            encoding="utf-8",
            check=True,
        ).stdout


def shoot(query, width, height, out, quality):
    with tempfile.TemporaryDirectory() as tmp:
        png = Path(tmp) / "shot.png"
        chrome(f"{BASE}?{query}&w={width}&h={height}", width, height, f"--screenshot={png}")
        img = Image.open(png).convert("RGB").crop((0, 0, width, height))
    out.parent.mkdir(parents=True, exist_ok=True)
    img.save(out, "JPEG", quality=quality, optimize=True, progressive=True)
    print(f"{out.relative_to(ROOT)}  {width}x{height}  {out.stat().st_size // 1024} KB")


def spots(query, width, height):
    dom = chrome(f"{BASE}?{query}&w={width}&h={height}", width, height, "--dump-dom")
    m = re.search(r'<pre id="capture-data"[^>]*>(.*?)</pre>', dom, re.S)
    if not m or not m.group(1).strip():
        sys.exit("no capture data in the page: is the server running and the scene rendering?")
    data = json.loads(html.unescape(m.group(1)))
    assert (data["width"], data["height"]) == (width, height), data
    return data["spots"]


# framed like the opening shot under the open overview, at a common laptop height
STILL = ("capture=still&time=14", 1600, 900)
# a closer shot, slid right so the title card on the left leaves the four labels clear
OG = ("capture=og&time=15&cam=-628,505,148,-68,0,-175", 1200, 630)

shoot(*STILL, ROOT / "public" / "fallback" / "campus.jpg", 80)
shoot(*OG, ROOT / "public" / "og.jpg", 86)

rows = "\n".join(
    f"    {{ module: '{s['module']}', x: {s['x']}, y: {s['y']} }}," for s in spots(*STILL)
)
(ROOT / "src" / "content" / "fallback.ts").write_text(
    f"""// Generated by scripts/capture_stills.py: the still of the campus shown when WebGL is unavailable,
// and where each module label points in it (image pixels).
import type {{ ModuleKey }} from '../data/campus'

export const FALLBACK: {{ image: string; width: number; height: number; spots: {{ module: ModuleKey; x: number; y: number }}[] }} = {{
  image: 'fallback/campus.jpg',
  width: {STILL[1]},
  height: {STILL[2]},
  spots: [
{rows}
  ],
}}
""",
    encoding="utf-8",
    newline="\n",
)
print("src/content/fallback.ts updated")
