// Builds src/content/worldLand.ts: a simplified world land outline (Natural Earth 1:110m via
// world-atlas) as one SVG path in an equirectangular projection, for the examples map in module 04.
import { readFile, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { feature } from 'topojson-client'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const require = createRequire(import.meta.url)
const topo = JSON.parse(await readFile(require.resolve('world-atlas/land-110m.json'), 'utf8'))

const W = 1000
const NORTH = 84
const SOUTH = -58 // leave Antarctica out
const H = Math.round(((NORTH - SOUTH) / 360) * W)
const x = (lon) => ((lon + 180) / 360) * W
const y = (lat) => ((NORTH - lat) / 360) * W

let d = ''
const land = feature(topo, topo.objects.land)
for (const f of land.features) {
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates
  for (const poly of polys) {
    for (const ring of poly) {
      if (ring.every(([, lat]) => lat < SOUTH)) continue
      let prev = ''
      ring.forEach(([lon, lat], i) => {
        const p = `${x(lon).toFixed(1)} ${y(Math.max(lat, SOUTH)).toFixed(1)}`
        if (p !== prev) d += (i === 0 ? 'M' : 'L') + p
        prev = p
      })
      d += 'Z'
    }
  }
}

const out = `// Generated by scripts/build-world-map.mjs from world-atlas (Natural Earth, public domain).
export const WORLD = { width: ${W}, height: ${H}, north: ${NORTH} }
export const WORLD_LAND = '${d}'
`
await writeFile(join(root, 'src', 'content', 'worldLand.ts'), out)
console.log(`worldLand.ts: ${(out.length / 1024).toFixed(0)} KB, ${W}×${H}`)
